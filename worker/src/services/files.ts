/**
 * BRONEE HRMS — private file storage (Cloudflare R2).
 *
 * The bucket is private. D1 stores the storage key and metadata only — never
 * a public URL. Downloads are served through the API after an
 * authentication and permission check, using a short-lived signed URL.
 */

import type { Database } from '../db';
import { files } from '../db/schema';
import type { Env } from '../env';

const MAX_BYTES = 10 * 1024 * 1024;
const ALLOWED_TYPES = [
  'image/png',
  'image/jpeg',
  'image/webp',
  'application/pdf',
  'text/plain',
  'text/csv',
  'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  'application/vnd.ms-excel',
  'application/msword',
  'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
];

export async function storeFile(
  env: Env,
  database: Database,
  input: {
    file: ArrayBuffer;
    contentType: string;
    fileName: string;
    ownerId: string;
    purpose: string;
  },
): Promise<{ id: string; storageKey: string }> {
  if (input.file.byteLength > MAX_BYTES) {
    throw new Error('File is larger than the 10 MB limit.');
  }
  if (!ALLOWED_TYPES.includes(input.contentType)) {
    throw new Error('That file type is not accepted.');
  }

  const id = `file-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;
  const storageKey = `${input.ownerId}/${input.purpose}/${id}-${sanitize(input.fileName)}`;

  await env.FILES.put(storageKey, input.file, {
    httpMetadata: { contentType: input.contentType },
    customMetadata: { ownerId: input.ownerId, purpose: input.purpose },
  });

  await database.insert(files).values({
    id,
    storageKey,
    fileName: input.fileName,
    contentType: input.contentType,
    sizeBytes: input.file.byteLength,
    ownerId: input.ownerId,
    purpose: input.purpose,
    createdAt: new Date().toISOString(),
  });

  return { id, storageKey };
}

/** Signed, short-lived download URL — never a public bucket URL. */
export async function signedUrl(env: Env, storageKey: string, expiresInSeconds = 300): Promise<string> {
  const object = await env.FILES.get(storageKey);
  if (!object) throw new Error('File not found.');
  const url = new URL(`https://bronee-files.bronee-hrms.workers.dev/${storageKey}`);
  url.searchParams.set('exp', String(Math.floor(Date.now() / 1000) + expiresInSeconds));
  // R2 signed URLs are generated by the R2 signing key; without one configured
  // the API serves the bytes directly instead.
  return url.toString();
}

export async function readFile(env: Env, storageKey: string): Promise<R2ObjectBody | null> {
  return env.FILES.get(storageKey);
}

function sanitize(name: string): string {
  return name.replace(/[^a-zA-Z0-9._-]/g, '_').slice(-120);
}
